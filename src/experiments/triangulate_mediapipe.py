
import numpy as np
import json
import cv2
from pathlib import Path

# --- CONFIG ---
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent

# Input Data
DATA_FILE_A = PROJECT_ROOT / "data" / "processed" / "data_mp_camA.json" # Cam 4
DATA_FILE_B = PROJECT_ROOT / "data" / "processed" / "data_mp_camB.json" # Cam 2

# Calibration Files
CAL_INT_CAM2 = PROJECT_ROOT / "cal/calibration_dec17/cam_2_intrinsics.json"
CAL_INT_CAM4 = PROJECT_ROOT / "cal/calibration_v2/cam4_intrinsics.json"
CAL_EXTRINSICS = PROJECT_ROOT / "cal/calibration_v2/extrinsics.json"

# Output
OUTPUT_FILE = PROJECT_ROOT / "data" / "processed" / "data_3d_mediapipe.json"

def load_json(path):
    with open(path, 'r') as f:
        return json.load(f)

def get_projection_matrix(K, R, T):
    # P = K @ [R|t]
    # R is 3x3, T is 3x1
    Rt = np.hstack((R, T.reshape(3, 1)))
    return K @ Rt

def main():
    print("--- 3D Triangulation (MediaPipe) ---")
    
    # 1. Load Data
    print("Loading 2D Data...")
    data_a = load_json(DATA_FILE_A)
    data_b = load_json(DATA_FILE_B)
    
    # Map by frame number for easy lookup
    # Cam A is Cam 4
    # Cam B is Cam 2
    frames_a = {d["frame"]: d for d in data_a}
    frames_b = {d["frame"]: d for d in data_b}
    
    common_frames = sorted(list(set(frames_a.keys()) & set(frames_b.keys())))
    print(f"Found {len(common_frames)} common frames.")
    
    # 2. Load Calibration
    print("Loading Calibration...")
    
    # Intrinsics
    int_cam2 = load_json(CAL_INT_CAM2) # Cam 2
    int_cam4 = load_json(CAL_INT_CAM4) # Cam 4
    
    K_cam2 = np.array(int_cam2["camera_matrix"])
    K_cam4 = np.array(int_cam4["camera_matrix"])
    
    # Extrinsics (World -> Camera)
    # The file contains relative transforms or absolute?
    # Usually "camX": { "matrix": ... } is World->Cam or Ref->Cam
    # Let's check logic:
    # Cam 4 is Cam A input
    # Cam 2 is Cam B input
    
    ext = load_json(CAL_EXTRINSICS)
    
    # Extract Matrices (4x4)
    M_cam2 = np.array(ext["transforms"]["cam2"]["matrix"])
    M_cam4 = np.array(ext["transforms"]["cam4"]["matrix"])
    
    # Decompose to R, T
    # Note: These M are likely World-to-Camera (Extrinsics) directly if generated by standard calibration
    # Verify if they are Cam-to-World?
    # Usually cal output is P = K * [R|t] * X
    # Let's assume M is the [R|t] block relative to Ref (Cam0)
    
    R_cam2 = M_cam2[:3, :3]
    T_cam2 = M_cam2[:3, 3] # This is in METERS in v2 file
    
    R_cam4 = M_cam4[:3, :3]
    T_cam4 = M_cam4[:3, 3] # This is in METERS
    
    # Convert T to MILLIMETERS to match standard (if needed, but usually we render in same units)
    # User previous pipeline used mm (render_3d_full had ZOOM=2000 mm)
    # So we should convert to mm to be safe.
    T_cam2 *= 1000.0
    T_cam4 *= 1000.0
    
    # Projection Matrices
    P_cam4 = get_projection_matrix(K_cam4, R_cam4, T_cam4) # Cam A
    P_cam2 = get_projection_matrix(K_cam2, R_cam2, T_cam2) # Cam B
    
    print("Projection Matrices Configured.")
    
    # 3. Triangulate
    # We will iterate frames and landmarks
    # MediaPipe structure:
    # pose: 33 pts
    # left_hand: 21 pts
    # right_hand: 21 pts
    # (face is huge, 468 pts, let's include it if present)
    
    # Total MP points mapping: 
    # Let's simple utilize separate lists in output
    
    result_data = []
    
    for f_idx in common_frames:
        frame_res = {"frame": f_idx}
        
        obs_a = frames_a[f_idx]
        obs_b = frames_b[f_idx]
        
        # Helper for a set of landmarks
        def triangulate_set(key):
            if key not in obs_a or key not in obs_b: return None
            
            pts_a = obs_a[key] # List of [x, y, z, vis] (Pose) or [x, y, z] (Hands)
            pts_b = obs_b[key]
            
            if len(pts_a) != len(pts_b): return None
            
            p3d_list = []
            
            # Prepare arrays for OpenCV triangulatePoints
            # We need 2xN arrays
            # Input is normalized [0,1]. Need to project to pixel coords!
            
            # Cam 4
            w4 = 1920 # HD
            h4 = 1080 
            # Cam 2
            w2 = 1920 
            h2 = 1080
            
            # Extract XY and denormalize
            uv_a = []
            uv_b = []
            
            for i in range(len(pts_a)):
                # MP x,y are normalized 0..1
                u_a, v_a = pts_a[i][0] * w4, pts_a[i][1] * h4
                u_b, v_b = pts_b[i][0] * w2, pts_b[i][1] * h2
                
                uv_a.append([u_a, v_a])
                uv_b.append([u_b, v_b])
                
            uv_a = np.array(uv_a).T # 2xN
            uv_b = np.array(uv_b).T # 2xN
            
            # Triangulate
            res_4d = cv2.triangulatePoints(P_cam4, P_cam2, uv_a, uv_b)
            # 4xN -> Divide by w
            res_3d = res_4d[:3, :] / res_4d[3, :]
            
            return res_3d.T.tolist() # Nx3 list
            
        frame_res["pose_3d"] = triangulate_set("pose")
        frame_res["left_hand_3d"] = triangulate_set("left_hand")
        frame_res["right_hand_3d"] = triangulate_set("right_hand")
        # frame_res["face_3d"] = triangulate_set("face") # Skip face for now to keep file size manageable?
        
        result_data.append(frame_res)
        
        if f_idx % 100 == 0:
            print(f"Triangulated frame {f_idx}")
            
    # 4. Save
    print(f"Saving 3D data to {OUTPUT_FILE}...")
    with open(OUTPUT_FILE, 'w') as f:
        json.dump(result_data, f)
    print("Done.")

if __name__ == "__main__":
    main()
